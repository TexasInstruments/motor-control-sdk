/**
 * \brief Prepare EnDAT3 request frames in TX buffer
 *
 * \details Constructs command and data frames in TX buffer with CRC calculation.
 *          Reverses byte order for transmission and validates buffer capacity.
 *
 * \param handle      EnDAT3 handle
 * \param cmd         Command byte to send
 * \param data_array  Pointer to array of data words (optional, can be NULL for command-only)
 * \param num_frames  Number of frames to send
 *
 * \retval ENDAT3_SUCCESS (0) on success
 * \retval ENDAT3_ERR_INVALID_INPUT (-1) if handle is NULL, invalid frame count, or buffer overflow
 *
 * \note Validation: Handle, and frame count (1 to ENDAT3_MAX_TX_FRAMES), and data_array
 * \note Each frame is 4 bytes: command/data(1) + data(2) + CRC(1)
 * \note CRC is calculated for each frame independently using \ref endat3_calculate_crc()
 * \note Byte order is reversed for PRU firmware consumption
 */
static int32_t endat3_prepare_request(endat3_handle handle, uint8_t cmd, volatile uint32_t *data_array, uint8_t num_frames)
{
    endat3_priv *priv;
    uint8_t i, k;
    uint8_t temp;
    uint8_t frame_length;

    /* Buffer overflow protection - check against actual buffer capacity (6) */
    if(num_frames > ENDAT3_MAX_TX_FRAMES || num_frames == 0)
    {
        return ENDAT3_ERR_INVALID_INPUT;  /* Invalid frame count (must be 1-6) */
    }

    if(data_array == NULL)
    {
        return ENDAT3_ERR_INVALID_INPUT;  /* Invalid data array pointer */
    }

    priv = handle->priv;

    /* Process frames, each 4 bytes long */
    for(k = 0; k < num_frames; k++)
    {
        /* Create request frame */
        priv->endat3_interface->tx_buffer[k * 4 + 0] = cmd;                            /* Command code */
        priv->endat3_interface->tx_buffer[k * 4 + 1] = data_array[k] & 0xFF;           /* LSB of data[k] */
        priv->endat3_interface->tx_buffer[k * 4 + 2] = (data_array[k] >> 8) & 0xFF;    /* MSB of data[k] */
        priv->endat3_interface->tx_buffer[k * 4 + 3] = endat3_calculate_crc(priv->endat3_interface->tx_buffer + k * 4, 3);

        /* Reverse byte order of the entire buffer (4 bytes: cmd, LSB, MSB, CRC) */
        frame_length = ENDAT3_FRAME_SIZE_BYTES;  /* Total frame length: command(1) + data(2) + CRC(1) */

        /* Swap bytes from outside toward the center */
        for(i = 0; i < frame_length / 2; i++)
        {
            temp = priv->endat3_interface->tx_buffer[k * 4 + i];
            priv->endat3_interface->tx_buffer[k * 4 + i] = priv->endat3_interface->tx_buffer[k * 4 + frame_length - 1 - i];
            priv->endat3_interface->tx_buffer[k * 4 + frame_length - 1 - i] = temp;
        }
    }

    return ENDAT3_SUCCESS;
}

/**
 * \brief Wait for and check EnDAT3 reception completion status
 *
 * \details Checks encoder busy status flag to determine if reception is complete.
 *          Detects encoder errors and busy status during communication.
 *
 * \param handle EnDAT3 handle
 *
 * \retval ENDAT3_SUCCESS (0) if reception completed successfully
 * \retval ENDAT3_ERR_INVALID_INPUT (-1) if handle is NULL
 * \retval ENDAT3_ERR_BUSY (-2) if encoder is still busy (transfer in progress)
 * \retval ENDAT3_ERR_SAMPLING_ERROR (-7) if encoder detected an error condition
 *
 * \note Validation: Handle pointer is validated
 * \note Encoder status: Checks busy flag (ENCODER_IDLE/ENCODER_BUSY/ENCODER_ERROR)
 * \note Caller should poll this function until success or implement timeout handling
 */
static int32_t endat3_wait_rx_complete(endat3_handle handle)
{
    endat3_priv *priv;

    priv = handle->priv;

    /* Return sampling error if encoder detected an error condition */
    if(priv->endat3_interface->busy == ENCODER_ERROR)
    {
        return ENDAT3_ERR_SAMPLING_ERROR;
    }
    /* Return busy status while a transfer is still in progress */
    if(priv->endat3_interface->busy == ENCODER_BUSY)
    {
        return ENDAT3_ERR_BUSY;
    }
    return ENDAT3_SUCCESS;
}

/**
 * \brief Parse received EnDAT3 frames from RX buffer
 *
 * \details Extracts HPF (High Priority Frame), LPH (Low Priority Header), and LPF (Low Priority Frames)
 *          from raw RX buffer into structured format. Copies data, status, and CRC fields.
 *
 * \param handle        EnDAT3 handle
 * \param rx_buffer     Pointer to RX buffer containing received frames (size of RX buffer must be >= 20 bytes)
 *
 * \retval ENDAT3_SUCCESS (0) on successful frame parsing
 * \retval ENDAT3_ERR_INVALID_INPUT (-1) if handle/rx_buffer is NULL or buffer too small
 *
 * \note Assumption: rx buffer length >= ENDAT3_MIN_RX_BUFFER_SIZE(20)
 * \note Validation: Handle, and rx_buffer pointer
 * \note Does not validate CRC - caller must use \ref endat3_validate_crc() for each frame
 * \note On validation failure, does not modify interface structures
 */
static int32_t endat3_parse_frames(endat3_handle handle, volatile uint8_t *rx_buffer)
{
    endat3_priv *priv;
    uint8_t i, j;

    priv = handle->priv;
    /* Parse HPF (bytes 0-7) - byte-by-byte copy to preserve volatile semantics */
    for(i = 0; i < HPF_DATA_SIZE; i++)
    {
        priv->endat3_interface->hpf.data[i] = rx_buffer[i];
    }
    priv->endat3_interface->hpf.status = rx_buffer[6];
    priv->endat3_interface->hpf.crc = rx_buffer[7];

    /* Parse LPH (bytes 8-11) */
    priv->endat3_interface->lph.status = rx_buffer[8];
    priv->endat3_interface->lph.num_lpf = rx_buffer[9];
    priv->endat3_interface->lph.crc = rx_buffer[11];

    /* Parse LPF[0] (bytes 12-19) */
    priv->endat3_interface->lpf[0].status = rx_buffer[12];  /* Copy status byte */

    /* Copy data payload byte by byte */
    for(j = 0; j < LPF_DATA_SIZE; j++)
    {
        priv->endat3_interface->lpf[0].data[j] = rx_buffer[13 + j];
    }

    priv->endat3_interface->lpf[0].crc = rx_buffer[19];  /* Copy CRC byte */

    return ENDAT3_SUCCESS;
}

