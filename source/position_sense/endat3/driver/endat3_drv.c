void endat3_params_init(endat3_params *params)
{
    if(params == NULL)
    {
        return;
    }

    /* Copy default parameters */
    *params = gEndat3DefaultParams;
}

endat3_handle endat3_init(uint32_t index, const endat3_params *params)
{
    int32_t             status = ENDAT3_SUCCESS;
    endat3_handle       handle = NULL;
    endat3_priv         *priv = NULL;
    const endat3_attrs  *attrs = NULL;
    endat3_clock_config clk_cfg;
    void                *base_addr = NULL;
    uint32_t            temp;

    /* Index and params validation */
    if((index >= gEndat3ConfigNum) || (params == NULL))
    {
        status = ENDAT3_ERR_INVALID_INPUT;
    }

    if(status == ENDAT3_SUCCESS)
    {
        handle = &gEndat3Handle[index];

        /* Get the pointer to the priv and attrs */
        priv = handle->priv;
        attrs = handle->attrs;

        /* Validate internal structures */
        if(priv == NULL || attrs == NULL)
        {
            /* Invalid internal structures */
            status = ENDAT3_ERR_INVALID_INPUT;
        }
    }

    if(status == ENDAT3_SUCCESS)
    {
        /* Validate params */
        if((params->pruicss_handle == NULL) ||
           (params->pruicss_handle->hwAttrs == NULL))
        {
            status = ENDAT3_ERR_INVALID_INPUT;
        }

        /* Validate all attrs members */
        if((attrs->instance >= gEndat3ConfigNum) ||
            (attrs->mode > ENDAT3_MODE_SINGLE_CHANNEL_SINGLE_PRU) ||
            (attrs->pruicss_instance > 1) ||
            (attrs->pruicss_slice > 1) ||
            (attrs->channel_mask == 0) ||
            (attrs->channel_mask > 0x7) ||
            (attrs->channel0_enabled > 1) ||
            (attrs->channel1_enabled > 1) ||
            (attrs->channel2_enabled > 1) ||
            (attrs->total_channels == 0) ||
            (attrs->total_channels > 3) ||
            (attrs->core_clk_freq == 0) ||
            (attrs->iep_clk_freq == 0) ||
            (attrs->iep_instance > 1) ||
            (attrs->iep_cmp_event >= ENDAT3_IEP_MAX_CMP_EVENT) ||
            (attrs->iep_cap_event >= ENDAT3_IEP_MAX_CAP_EVENT) ||
            (attrs->iep_base_addr == NULL))
        {
            status = ENDAT3_ERR_INVALID_INPUT;
        }

        /* Validate baud_rate - must be one of the supported EnDAT3 modes */
        if((attrs->baud_rate != ENDAT3_BAUD_RATE_12_5_MBPS))
        {
            status = ENDAT3_ERR_INVALID_INPUT;
        }

        /* Validate core_clk_freq - must be one of the supported EnDAT3 frequencies */
        if((attrs->core_clk_freq != ENDAT3_CORE_CLK_200MHZ) && (attrs->core_clk_freq != ENDAT3_CORE_CLK_300MHZ))
        {
            status = ENDAT3_ERR_INVALID_INPUT;
        }
    }

    if(status == ENDAT3_SUCCESS)
    {
        priv->pruicss_handle = params->pruicss_handle;

        /* Set base memory address based on PRU slice */
        if(attrs->pruicss_slice)
        {
            priv->base_mem_addr = (uint32_t *)(((PRUICSS_HwAttrs *)(priv->pruicss_handle->hwAttrs))->pru1DramBase);
        }
        else
        {
            priv->base_mem_addr = (uint32_t *)(((PRUICSS_HwAttrs *)(priv->pruicss_handle->hwAttrs))->pru0DramBase);
        }

        priv->endat3_interface = (endat3_interface *)(priv->base_mem_addr);

        endat3_generate_memory_image(handle);

        /* Set delay cycles based on PRU frequency */
        status = endat3_set_delay_cycles(handle);
    }

    if(status == ENDAT3_SUCCESS)
    {
        /*Set IEP base address */
        base_addr = (void *)((PRUICSS_HwAttrs *)(handle->priv->pruicss_handle->hwAttrs))->baseAddr;
        temp = ((uint32_t)attrs->iep_base_addr) - ((uint32_t)base_addr);

        /* Initialize IEP base address in endat3_interface */
        status = endat3_config_iep_base_address(handle, temp);
    }

    if(status == ENDAT3_SUCCESS)
    {
        status = endat3_config_iep_cmp_event(handle, attrs->iep_cmp_event);
    }

    if(status == ENDAT3_SUCCESS)
    {
        status = endat3_config_iep_cap_event(handle, attrs->iep_cap_event);
    }

    if(status == ENDAT3_SUCCESS)
    {
        /* Set channel mask */
        status = endat3_set_channel_mask(handle, attrs->channel_mask);
    }

    if(status == ENDAT3_SUCCESS)
    {
        /* Configure EnDAT mode */
        if(PRUICSS_setGpMuxSelect(priv->pruicss_handle, attrs->pruicss_slice, PRUICSS_GP_MUX_SEL_MODE_ENDAT) != SystemP_SUCCESS)
        {
            status = ENDAT3_ERR_INVALID_INPUT;
        }
    }

    if(status == ENDAT3_SUCCESS)
    {
        /* Clear CFG0 registers for enabled channels */
        status = endat3_config_clr_cfg0(handle);
    }

    if(status == ENDAT3_SUCCESS)
    {
        status = endat3_calculate_clock(handle, &clk_cfg);
    }

    if(status == ENDAT3_SUCCESS)
    {
        status = endat3_config_clock(handle, &clk_cfg);
    }

    if(status == ENDAT3_SUCCESS)
    {
        status = endat3_set_operating_mode(handle, ENDAT3_OPMODE_HOST_TRIGGER);
    }

    if(status == ENDAT3_SUCCESS)
    {
        /* Mark handle as open after successful initialization */
        priv->is_open = 1;
    }
    else
    {
        handle = NULL;
    }

    return handle;
}

void endat3_deinit(endat3_handle handle)
{
    endat3_priv *priv;

    if((handle == NULL) || (handle->priv == NULL))
    {
        return;
    }

    priv = handle->priv;
    /* Mark as closed */
    priv->is_open = 0;
}

const endat3_attrs* endat3_get_attrs(endat3_handle handle)
{
    if((handle == NULL) || (handle->attrs == NULL))
    {
        return NULL;
    }

    return handle->attrs;
}

