int32_t endat3_send_command(endat3_handle handle, uint8_t cmd, uint8_t frames)
{
    endat3_priv *priv;
    int32_t status;

    /* Validate handle and internal structure pointers */
    if((handle == NULL) || (handle->priv == NULL) || (handle->priv->endat3_interface == NULL))
    {
        return ENDAT3_ERR_INVALID_INPUT;
    }

    priv = handle->priv;

    /* Prepare request frame */
    status = endat3_prepare_request(handle, cmd, priv->endat3_interface->bg_data, frames);

    if(status != ENDAT3_SUCCESS)
    {
        return status;
    }

    return ENDAT3_SUCCESS;
}

int32_t endat3_receive_response(endat3_handle handle)
{
    endat3_priv *priv;
    int32_t status;

    /* Validate handle and internal structure pointers */
    if((handle == NULL) || (handle->priv == NULL) || (handle->priv->endat3_interface == NULL))
    {
        return ENDAT3_ERR_INVALID_INPUT;
    }

    priv = handle->priv;

    /* Wait for RX complete */
    status = endat3_wait_rx_complete(handle);
    if(status != ENDAT3_SUCCESS)
    {
        return status;
    }

    /* Parse received frames */
    status = endat3_parse_frames(handle, priv->endat3_interface->rx_buffer);
    if(status != ENDAT3_SUCCESS)
    {
        return status;
    }

    /* HPF CRC check */
    status = endat3_validate_crc(priv->endat3_interface->rx_buffer + ENDAT3_HPF_OFFSET, ENDAT3_HPF_TOTAL_SIZE);
    if(status != ENDAT3_SUCCESS)
    {
        return ENDAT3_ERR_HPF_CRC_FAIL;
    }

    /* LPH CRC check */
    status = endat3_validate_crc(priv->endat3_interface->rx_buffer + ENDAT3_LPH_OFFSET, ENDAT3_LPH_TOTAL_SIZE);
    if(status != ENDAT3_SUCCESS)
    {
        return ENDAT3_ERR_LPH_CRC_FAIL;
    }

    /* check for SENDLIST 0 to calculate CRC for LPF only */
    if(priv->endat3_interface->tx_buffer[3] == 0)
    {
        /* LPF CRC check for SENDLIST 0 */
        status = endat3_validate_crc(priv->endat3_interface->rx_buffer + ENDAT3_LPF_OFFSET, ENDAT3_LPF_TOTAL_SIZE);
        if(status != ENDAT3_SUCCESS)
        {
            return ENDAT3_ERR_LPF_CRC_FAIL;
        }
    }

    return ENDAT3_SUCCESS;
}

/**
 * \brief Reflect (reverse) bits in a value
 *
 * \details Reverses the bit order of a value within the specified width.
 *          Used for CRC calculations that require bit reflection.
 *
 * \param value Value to reflect
 * \param width Number of bits to reflect (e.g., 8 for byte, 16 for word)
 *
 * \return Bit-reflected value
 */
static uint16_t endat3_reflect_general(uint16_t value, uint16_t width)
{
    uint16_t result = 0;
    uint16_t i;

    for(i = 0; i < width; i++)
    {
        if((value & (1 << i)) != 0)
        {
            result |= (1 << (width - 1 - i));
        }
    }
    return result;
}

/**
 * \brief Generic CRC computation with configurable parameters
 *
 * \details Computes CRC using customizable polynomial, width, initial value, and reflection options.
 *
 * \param bytes           Input data buffer
 * \param length          Number of bytes to process
 * \param poly            CRC polynomial
 * \param crcsize         CRC width in bits
 * \param initialValue    Initial CRC register value
 * \param inputReflected  1 to reflect input bytes, 0 otherwise
 * \param resultReflected 1 to reflect final CRC, 0 otherwise
 * \param finalXor        Value to XOR with final CRC
 *
 * \return Computed CRC value
 */
static uint16_t endat3_compute_crc(const volatile uint8_t *bytes, size_t length,
                          uint16_t poly, uint16_t crcsize,
                          uint16_t initialValue, uint8_t inputReflected,
                          uint8_t resultReflected, uint16_t finalXor)
{
    /* Calculate bit manipulation constants */
    uint16_t bits_to_shift = crcsize - 8;       /* How many bits to shift input byte */
    uint16_t bit_mask = 1 << (crcsize - 1);     /* Mask for MSB check */
    uint16_t final_mask = (1 << crcsize) - 1;   /* Mask for final value */
    uint16_t crc = initialValue;
    size_t j;
    uint16_t i;
    uint8_t cur_byte;

    /* Process each input byte */
    for(j = 0; j < length; j++)
    {
        /* Reflect input byte if needed */
        cur_byte = inputReflected ? (uint8_t)endat3_reflect_general(bytes[j], 8) : bytes[j];

        /* XOR the byte into the MSB of CRC register */
        crc ^= (uint16_t)(cur_byte << bits_to_shift);

        /* Process each bit */
        for(i = 0; i < 8; i++)
        {
            if((crc & bit_mask) != 0)
            {
                /* MSB is set, shift left and XOR with polynomial */
                crc = (uint16_t)((crc << 1) ^ poly);
            }
            else
            {
                /* MSB not set, just shift left */
                crc <<= 1;
            }
        }

        /* Apply final mask to keep only relevant bits */
        crc = crc & final_mask;
    }

    /* Reflect result if needed */
    if(resultReflected)
    {
        crc = endat3_reflect_general(crc, crcsize);
    }

    /* Apply final XOR */
    crc ^= finalXor;

    return crc & final_mask;
}

/**
 * \brief Calculate EnDAT3 protocol-specific CRC-8
 *
 * \details Computes CRC-8 for EnDAT3 protocol using fixed parameters:
 *          polynomial=0xA7, initial=0xFF, input/result reflected, finalXor=0x00.
 *          This is a wrapper around \ref endat3_compute_crc() with EnDAT3-specific settings.
 *
 * \param data Pointer to input data buffer
 * \param len  Number of bytes to process
 *
 * \return 8-bit CRC value
 */
static uint8_t endat3_calculate_crc(const volatile uint8_t *data, uint32_t len)
{
    /* CRC parameters: polynomial=0xA7, crcsize=8, initialValue=0xFF,
     * inputReflected=1, resultReflected=1, finalXor=0x00 */
    return ((uint8_t)endat3_compute_crc(data, len, 0xA7, 8, 0xFF, 1, 1, 0x00));
}

/**
 * \brief Validate CRC of received EnDAT3 frame
 *
 * \details Extracts CRC from last byte of buffer, recalculates CRC for data bytes,
 *          and compares for integrity verification. Returns generic error on mismatch
 *          so caller can set specific error context (HPF/LPH/LPF).
 *
 * \param buffer Pointer to frame buffer (data + CRC byte)
 * \param length Total frame length including CRC byte (must be >= 2)
 *
 * \retval ENDAT3_SUCCESS (0) if CRC matches (frame valid)
 * \retval ENDAT3_ERR_INVALID_INPUT (-1) if buffer length < 2
 * \retval ENDAT3_ERR_RX_FAIL (-3) if CRC mismatch (caller should set specific error)
 *
 * \note Assumption: buffer is a valid pointer and not NULL
 * \note Validation: Frame length must be >= 2 (at least 1 data byte + 1 CRC byte)
 * \note CRC calculation: Uses \ref endat3_calculate_crc() on all bytes except last
 * \note Generic error: Returns ENDAT3_ERR_RX_FAIL on CRC failure, not frame-specific error
 */
static int32_t endat3_validate_crc(const volatile uint8_t *buffer, uint32_t length)
{
    uint8_t received_crc;
    uint8_t calculated_crc;

    /* A valid frame must contain at least one data byte and a CRC byte */
    if(length <= 1)
    {
        return ENDAT3_ERR_INVALID_INPUT;  /* Invalid frame length */
    }

    received_crc = buffer[length - 1];
    calculated_crc = endat3_calculate_crc(buffer, length - 1);

    /* Return generic error - caller sets specific CRC error context (HPF/LPH/LPF) */
    return ((received_crc == calculated_crc) ? ENDAT3_SUCCESS : ENDAT3_ERR_RX_FAIL);
}

/**
 * \brief Clear CFG0 registers for enabled EnDAT3 channels
 *
 * \details Clears (writes 0) to PRU-ICSS CFG0 registers for all enabled channels.
 *          CFG0 registers control channel-specific configuration and must be cleared
 *          before initializing EnDAT3 communication.
 *
 * \param handle EnDAT3 handle
 *
 * \retval ENDAT3_SUCCESS (0) on success
 * \retval ENDAT3_ERR_INVALID_INPUT (-1) if handle is NULL
 *
 * \note Validation: Handle pointer is validated
 * \note Hardware access: Clears PRUx_ED_CHy_CFG0_REG for each enabled channel
 * \note PRU slice determines which register set (PRU0 or PRU1) is accessed
 */
static int32_t endat3_config_clr_cfg0(endat3_handle handle)
{
    endat3_priv         *priv;
    const endat3_attrs  *attrs;
    void                *pruicss_cfg;

    priv = handle->priv;
    attrs = handle->attrs;
    pruicss_cfg = (void *)(((PRUICSS_HwAttrs *)(priv->pruicss_handle->hwAttrs))->cfgRegBase);

    if(attrs->pruicss_slice)
    {
        if(attrs->channel0_enabled)
        {
            HW_WR_REG32((uint8_t *)pruicss_cfg + CSL_ICSS_PR1_CFG_SLV_PRU1_ED_CH0_CFG0_REG, 0);
        }
        if(attrs->channel1_enabled)
        {
            HW_WR_REG32((uint8_t *)pruicss_cfg + CSL_ICSS_PR1_CFG_SLV_PRU1_ED_CH1_CFG0_REG, 0);
        }
        if(attrs->channel2_enabled)
        {
            HW_WR_REG32((uint8_t *)pruicss_cfg + CSL_ICSS_PR1_CFG_SLV_PRU1_ED_CH2_CFG0_REG, 0);
        }
    }
    else
    {
        if(attrs->channel0_enabled)
        {
            HW_WR_REG32((uint8_t *)pruicss_cfg + CSL_ICSS_PR1_CFG_SLV_PRU0_ED_CH0_CFG0_REG, 0);
        }
        if(attrs->channel1_enabled)
        {
            HW_WR_REG32((uint8_t *)pruicss_cfg + CSL_ICSS_PR1_CFG_SLV_PRU0_ED_CH1_CFG0_REG, 0);
        }
        if(attrs->channel2_enabled)
        {
            HW_WR_REG32((uint8_t *)pruicss_cfg + CSL_ICSS_PR1_CFG_SLV_PRU0_ED_CH2_CFG0_REG, 0);
        }
    }
    return ENDAT3_SUCCESS;
}

/**
 * \brief Calculate and set timing delay cycles for EnDAT3 communication
 *
 * \details Scales reference delay values based on actual PRU core clock frequency.
 *          Computes delays for TX start, RX start, propagation time measurement, and CRC calculation.
 *          All reference delays are defined for 1MHz base frequency and scaled to actual frequency.
 *
 * \param handle EnDAT3 handle
 *
 * \retval ENDAT3_SUCCESS (0) on success
 * \retval ENDAT3_ERR_INVALID_INPUT (-1) if handle is NULL
 *
 * \note Validation: Handle pointer is validated
 * \note Scaling formula: actual_cycles = (reference_cycles * actual_freq) / 1MHz
 * \note Delay types: TX start delays, RX start delays, propagation time delays, CRC delays
 */
static int32_t endat3_set_delay_cycles(endat3_handle handle)
{
    endat3_priv         *priv;
    uint64_t            core_clk_freq;

    priv = handle->priv;
    core_clk_freq = handle->attrs->core_clk_freq;
    /* Scale delay values based on actual PRU frequency relative to 1MHz reference.
     * Formula: actual_cycles = (reference_cycles * actual_freq) / reference_freq
     * Reference values are defined as macros and represent cycles at 1MHz base frequency.
     *
     * 64-bit arithmetic prevents overflow: Cast to uint64_t ensures safe intermediate result before division scales back to uint32_t range
     */

    priv->endat3_interface->delay_tx_start_1    = (uint32_t)(((uint64_t)ENDAT3_TX_START_DELAY_1_REF_CYCLES * core_clk_freq) / REFERENCE_PRU_FREQ_HZ);
    priv->endat3_interface->delay_tx_start_2    = (uint32_t)(((uint64_t)ENDAT3_TX_START_DELAY_2_REF_CYCLES * core_clk_freq) / REFERENCE_PRU_FREQ_HZ);
    priv->endat3_interface->delay_tx_start_3    = (uint32_t)(((uint64_t)ENDAT3_TX_START_DELAY_3_REF_CYCLES * core_clk_freq) / REFERENCE_PRU_FREQ_HZ);
    priv->endat3_interface->delay_10ms          = (uint32_t)(((uint64_t)ENDAT3_DELAY_10MS_REF_CYCLES * core_clk_freq) / REFERENCE_PRU_FREQ_HZ);

    priv->endat3_interface->delay_sampling      = (uint32_t)(core_clk_freq / REFERENCE_PRU_FREQ_HZ_FOR_SAMPLING);

    return ENDAT3_SUCCESS;
}

/**
 * \brief Set channel enable mask for EnDAT3 communication
 *
 * \details Configures which encoder channels (0-2) are enabled for communication.
 *          The mask is written to firmware interface structure for PRU firmware to use.
 *
 * \param handle       EnDAT3 handle
 * \param channel_mask Channel enable mask (bit 0=CH0, bit 1=CH1, bit 2=CH2)
 *
 * \retval ENDAT3_SUCCESS (0) on success
 * \retval ENDAT3_ERR_INVALID_INPUT (-1) if handle is NULL or channel_mask is not in required range
 */
static int32_t endat3_set_channel_mask(endat3_handle handle, uint8_t channel_mask)
{
    endat3_priv *priv;

    if((channel_mask == 0) || (channel_mask > ENDAT3_CHANNEL_MASK_MAX))
    {
        return ENDAT3_ERR_INVALID_INPUT;
    }

    priv = handle->priv;

    /* Set channel enable mask in firmware interface structure
     * Bit 0: Channel 0 enable
     * Bit 1: Channel 1 enable
     * Bit 2: Channel 2 enable
     */
    priv->endat3_interface->channel_enable_mask = channel_mask;

    return ENDAT3_SUCCESS;
}

int32_t endat3_handle_background_command_request(endat3_handle handle, const endat3_bg_cmd_params *params, uint8_t *mode, const char **acc_level_desc)
{
    endat3_priv *priv;
    uint8_t     index;
    uint8_t     frame_cnt;
    uint8_t     op_code;
    uint32_t    addr_msb;
    uint32_t    addr_lsb;
    uint32_t    data;
    uint8_t     mode_val = 0;
    const char  *acc_level_desc_val = NULL;
    uint8_t     acclevel;

    /* Validate handle, parameters, and internal structure pointers */
    /* Validate index bounds (bg_data array has 6 elements, each command uses 4 indices starting at index) */

    if((handle == NULL) || (params == NULL) || (handle->priv == NULL) || (handle->priv->endat3_interface == NULL) || (params->index >= ENDAT3_MAX_BG_CMD_INDEX))
    {
        return ENDAT3_ERR_INVALID_INPUT;
    }

    priv = handle->priv;

    /* Extract parameters from struct */
    index = params->index;
    frame_cnt = params->frame_cnt;
    op_code = params->op_code;
    addr_msb = params->addr_msb;
    addr_lsb = params->addr_lsb;
    data = params->data;

    switch(op_code)
    {
        case ENDAT3_BGREQ_NOP:
            /* NOP operation: Just need to send arbitrary data */
            priv->endat3_interface->bg_data[index + 0] = data & 0xFFFF;              /* Arbitrary data */
            priv->endat3_interface->bg_data[index + 1] = (data >> 16) & 0xFFFF;       /* Arbitrary data */
            priv->endat3_interface->bg_data[index + 2] = (ENDAT3_BGREQ_NOP << 8);         /* OpCode */
            break;

        case ENDAT3_BGREQ_READ:
            /* READ operation: addr_msb = address[23:16], addr_lsb = address[15:0], data = num_words */
            priv->endat3_interface->bg_data[index + 0] = data & 0xFF;                                          /* num_words */
            priv->endat3_interface->bg_data[index + 1] = addr_lsb & 0xFFFF;                                    /* address[15:0] */
            priv->endat3_interface->bg_data[index + 2] = (addr_msb & 0xFF) | (ENDAT3_BGREQ_READ << 8);        /* OpCode + address[23:16] */
            break;

        case ENDAT3_BGREQ_WRITE:
            /* WRITE operation: addr_msb = address[23:16], addr_lsb = address[15:0], data = value to write */
            priv->endat3_interface->bg_data[index + 0] = data & 0xFFFF;                                        /* Word to write */
            priv->endat3_interface->bg_data[index + 1] = addr_lsb & 0xFFFF;                                    /* address[15:0] */
            priv->endat3_interface->bg_data[index + 2] = (addr_msb & 0xFF) | (ENDAT3_BGREQ_WRITE << 8);       /* OpCode + address[23:16] */
            break;

        case ENDAT3_BGREQ_RECONFIGURE:
            /* RECONFIGURE operation: Simply sends the reconfigure command */
            priv->endat3_interface->bg_data[index + 0] = 0x0000;                       /* Reserved (0) */
            priv->endat3_interface->bg_data[index + 1] = 0x0000;                       /* Reserved (0) */
            priv->endat3_interface->bg_data[index + 2] = ENDAT3_BGREQ_RECONFIGURE << 8;  /* OpCode */
            break;

        case ENDAT3_BGREQ_AUTH:
            /* AUTH operation: addr_msb = usrlevel, addr_lsb/data = password */
            priv->endat3_interface->bg_data[index + 0] = data & 0xFFFF;                                  /* Password part 2 */
            priv->endat3_interface->bg_data[index + 1] = addr_lsb & 0xFFFF;                              /* Password part 1 */
            priv->endat3_interface->bg_data[index + 2] = (addr_msb & 0xFF) | (ENDAT3_BGREQ_AUTH << 8);  /* OpCode + User level */
            break;

        case ENDAT3_BGREQ_PROTECT:
        {
            /*
             * PROTECT operation with 2-byte bg_data entries:
             * bg_data[index+0]: Bytes 0-1 (acclevel, mode)
             * bg_data[index+1]: Bytes 2-3 (address[15:0])
             * bg_data[index+2]: Bytes 4-5 (address[23:16], OpCode=0x81)
             */
            mode_val = (data >> 24) & 0xFF;
            acclevel = (data >> 16) & 0xFF;

            /* Pack the first 2 bytes: acclevel (byte 0) and mode (byte 1) */
            priv->endat3_interface->bg_data[index + 0] = (mode_val << 8) | acclevel;

            /* Pack the middle 2 bytes: address[15:0] (bytes 2-3) */
            priv->endat3_interface->bg_data[index + 1] = addr_lsb & 0xFFFF;

            /* Pack the last 2 bytes: address[23:16] (byte 4) and OpCode=0x81 (byte 5) */
            priv->endat3_interface->bg_data[index + 2] = (0x81 << 8) | (addr_msb & 0xFF);

            /* Get description for access level */
            switch(acclevel)
            {
                case 0:
                    acc_level_desc_val = "USER";
                    break;
                case 1:
                    acc_level_desc_val = "OEM2";
                    break;
                case 2:
                    acc_level_desc_val = "OEM1";
                    break;
                case 3:
                    acc_level_desc_val = "MANUFACTURER";
                    break;
                default:
                    acc_level_desc_val = "Unknown";
                    break;
            }

            break;
        }

        case ENDAT3_BGREQ_SETPASS:
            /* SETPASS operation: addr_msb = usrlevel, addr_lsb/data = password */
            priv->endat3_interface->bg_data[index + 0] = data & 0xFFFF;                                     /* Password part 2 */
            priv->endat3_interface->bg_data[index + 1] = addr_lsb & 0xFFFF;                                 /* Password part 1 */
            priv->endat3_interface->bg_data[index + 2] = (addr_msb & 0xFF) | (ENDAT3_BGREQ_SETPASS << 8);  /* OpCode + User level */
            break;

        case ENDAT3_BGREQ_LOCATE:
            /* LOCATE operation: addr_msb = not used, addr_lsb = not used, data = ctrl */
            priv->endat3_interface->bg_data[index + 0] = data & 0xFF;                  /* ctrl */
            priv->endat3_interface->bg_data[index + 1] = 0x0000;                       /* Reserved (0) */
            priv->endat3_interface->bg_data[index + 2] = ENDAT3_BGREQ_LOCATE << 8;     /* OpCode */
            break;

        default:
            /* Invalid operation code, use NOP */
            priv->endat3_interface->bg_data[index + 0] = 0x0000;               /* Arbitrary data */
            priv->endat3_interface->bg_data[index + 1] = 0x0000;               /* Arbitrary data */
            priv->endat3_interface->bg_data[index + 2] = ENDAT3_BGREQ_NOP << 8;  /* OpCode */
            break;
    }

    /* BG_DATAT=0 for last frame in which we receive BG response in LPFs */
    priv->endat3_interface->bg_data[index + 3] = 0x0;
    /* Set the frame count for all operations */
    priv->endat3_interface->expected_tx_frames_count = frame_cnt;
    if(op_code == ENDAT3_BGREQ_RECONFIGURE)
    {
        priv->endat3_interface->expected_tx_frames_count++;
    }
    /* Populate output parameters if provided */
    if(mode != NULL)
    {
        *mode = mode_val;
    }
    if(acc_level_desc != NULL)
    {
        *acc_level_desc = acc_level_desc_val;
    }

    return ENDAT3_SUCCESS;
}

